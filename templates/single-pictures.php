<?php
/**
 * Single picture collection template.
 *
 * @package InfinitePictureGallery
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

get_header();
?>

<main id="primary" class="site-main ipg-site-main">
	<div class="ipg-single-wrapper">
		<?php while ( have_posts() ) : ?>
			<?php the_post(); ?>
			<article id="post-<?php the_ID(); ?>" <?php post_class( 'ipg-single-article' ); ?>>
				<header class="ipg-single-header">
					<?php
					$title = get_the_title();
					if ( ! empty( $title ) && '(no title)' !== $title ) :
						?>
						<h1 class="ipg-single-title"><?php echo esc_html( $title ); ?></h1>
					<?php endif; ?>
					<div class="ipg-single-date">
						<?php
						printf(
							/* translators: %s: Publication date. */
							esc_html__( 'Added on %s', 'infinite-picture-gallery' ),
							esc_html( get_the_date( 'F j, Y' ) )
						);
						?>
					</div>
				</header>

				<div class="ipg-single-content">
					<?php if ( has_post_thumbnail() ) : ?>
						<div class="ipg-cover-media">
							<?php
							$cover = get_the_post_thumbnail( get_the_ID(), 'large', array( 'class' => 'ipg-cover-image' ) );
							// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress core for the current post.
							echo $cover;
							?>
						</div>
					<?php endif; ?>

					<?php
					$description = get_post_meta( get_the_ID(), Infinite_Picture_Gallery::DESCRIPTION_META_KEY, true );
					if ( ! empty( $description ) ) :
						?>
						<div class="ipg-description">
							<?php echo wp_kses_post( wpautop( $description ) ); ?>
						</div>
					<?php endif; ?>
				</div>

				<?php
				$gallery_ids = get_post_meta( get_the_ID(), Infinite_Picture_Gallery::GALLERY_META_KEY, true );
				$ids_array   = array_values( array_filter( array_map( 'absint', explode( ',', (string) $gallery_ids ) ) ) );
				if ( ! empty( $ids_array ) ) :
					?>
					<div class="ipg-inner-gallery-grid">
						<?php foreach ( $ids_array as $attachment_id ) : ?>
							<?php if ( wp_attachment_is( 'video', $attachment_id ) ) : ?>
								<?php
								$video_url = wp_get_attachment_url( $attachment_id );
								$mime_type = get_post_mime_type( $attachment_id );
								if ( ! $video_url ) {
									continue;
								}
								?>
								<video controls playsinline preload="metadata">
									<source src="<?php echo esc_url( $video_url ); ?>#t=0.5" type="<?php echo esc_attr( $mime_type ); ?>">
									<?php esc_html_e( 'Your browser does not support the video tag.', 'infinite-picture-gallery' ); ?>
								</video>
							<?php else : ?>
								<?php
								$image = wp_get_attachment_image( $attachment_id, 'large', false, array( 'loading' => 'lazy' ) );
								// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress core for a known attachment ID.
								echo $image;
								?>
							<?php endif; ?>
						<?php endforeach; ?>
					</div>
				<?php endif; ?>

				<div class="ipg-back-row">
					<a class="ipg-back-link" href="<?php echo esc_url( Infinite_Picture_Gallery::get_gallery_url() ); ?>">
						<span aria-hidden="true">&larr;</span>
						<?php esc_html_e( 'Back to Gallery', 'infinite-picture-gallery' ); ?>
					</a>
				</div>
			</article>
		<?php endwhile; ?>
	</div>
</main>

<?php get_footer(); ?>
